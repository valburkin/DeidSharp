using System.Text;

namespace DeidSharp.Evaluation.Cli.Reporting;

/// <summary>
/// The results at a glance in the repository's README, rendered from results.json between two
/// marker comments: recall and precision of the headline stacks (<see cref="HeadlineStacks"/>)
/// on each corpus, so a reader sees the trade-off, not one number. The rest of the page is
/// written by hand.
/// </summary>
internal static class ResultsGlance
{
    public const string Begin = "<!-- glance:begin (generated by DeidSharp.Evaluation.Cli from docs/evaluation/results.json; do not edit) -->";
    public const string End = "<!-- glance:end -->";

    private static readonly MarkedSection Markers = new(Begin, End, "The repository README has only one of its glance markers, or has them out of order; restore them from Git or remove both.");

    public static bool HasSection(string page) => Markers.IsIn(page);

    /// <summary>The page with its glance section replaced by <paramref name="results"/>.</summary>
    public static string Update(string page, PublishedResults results) => Markers.Replace(page, Render(results));

    /// <summary>The page's current glance section, markers included.</summary>
    public static string Current(string page) => Markers.Current(page);

    public static string Render(PublishedResults results)
    {
        ArgumentNullException.ThrowIfNull(results);
        var columns = HeadlineStacks.Corpora.Select(c => (c.Label, Result: HeadlineStacks.Find(results, c.Corpus, c.Split))).ToList();
        var md = new StringBuilder().Append(Begin).Append("\n\n| Recall / precision | ")
            .AppendJoin(" | ", columns.Select(c => c.Label))
            .Append(" |\n|---|")
            .Append(string.Concat(columns.Select(_ => "---:|")))
            .Append('\n');
        foreach (var (label, stack) in HeadlineStacks.Stacks)
        {
            md.Append("| ").Append(label).Append(" | ")
                .AppendJoin(" | ", columns.Select(c => c.Result?.Stacks.FirstOrDefault(s => s.Stack == stack) is { } found
                    ? $"{Formats.Percent(found.Recall)} / {Formats.Percent(found.Precision)}"
                    : "not measured"))
                .Append(" |\n");
        }

        var builds = columns.Where(c => c.Result is not null).Select(c => Build(c.Result!)).Distinct(StringComparer.Ordinal).ToList();
        md.Append("\nThe held-out halves of the nursing notes and the discharge summaries, and all of ASQ-PHI, in the Safe Harbor scope")
            .Append(builds.Count > 0 ? $"; measured with {string.Join(" and ", builds)}" : "")
            .Append(".\n\n")
            .Append(End);
        return md.ToString();
    }

    private static string Build(CorpusResult result) =>
        result.BuildLabel() + (result.LanguageModels is { } models ? $", LLM {models.Describe()}" : "");
}
