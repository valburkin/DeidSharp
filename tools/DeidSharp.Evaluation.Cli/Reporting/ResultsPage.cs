using System.Text;

namespace DeidSharp.Evaluation.Cli.Reporting;

/// <summary>
/// The results section of docs/evaluation/README.md, rendered from results.json between two
/// marker comments. The rest of the page is written by hand.
/// </summary>
internal static class ResultsPage
{
    public const string Begin = "<!-- results:begin (generated by DeidSharp.Evaluation.Cli from results.json; do not edit) -->";
    public const string End = "<!-- results:end -->";

    private static readonly MarkedSection Markers = new(Begin, End, "The results page has lost its results markers; restore them from Git.");

    /// <summary>The page with its results section replaced by <paramref name="results"/>.</summary>
    public static string Update(string page, PublishedResults results) => Markers.Replace(page, Render(results));

    public static bool HasSection(string page) => Markers.IsIn(page);

    /// <summary>The page's current results section, markers included.</summary>
    public static string Current(string page) => Markers.Current(page);

    public static string Render(PublishedResults results)
    {
        ArgumentNullException.ThrowIfNull(results);
        var md = new StringBuilder().Append(Begin).Append('\n');
        if (results.Corpora.Count == 0)
        {
            md.Append("\nNo results yet.\n");
        }

        foreach (var corpus in results.Corpora)
        {
            Corpus(md, corpus);
        }

        return md.Append('\n').Append(End).ToString();
    }

    private static void Corpus(StringBuilder md, CorpusResult corpus)
    {
        md.Append("\n### ").Append(corpus.Title).Append("\n\n")
            .Append(Formats.Invariant($"{corpus.Documents:N0} documents · {corpus.GoldSpans:N0} gold spans · scope `{corpus.Scope}` · split `{corpus.Split}` · {corpus.BuildLabel()} · {corpus.Date:yyyy-MM-dd}"))
            .Append(corpus.LanguageModels is { } models ? $" · LLM {models.Describe()}" : "")
            .Append(corpus.Note is { } note ? $" · {note}" : "")
            .Append("\n\n| Stack | Recall (95% CI) | Character recall | Precision | Word F1 | Non-PHI removed | Missed |\n|---|---:|---:|---:|---:|---:|---:|\n");
        foreach (var stack in corpus.Stacks)
        {
            var recall = stack.Intervals is { } i
                ? $"{Formats.Percent(stack.Recall)} ({Formats.Range(i.Recall.Low, i.Recall.High)})"
                : Formats.Percent(stack.Recall);
            md.Append(Formats.Invariant(
                $"| {stack.Stack} | {recall} | {Formats.Percent(stack.CharacterRecall)} | {Formats.Percent(stack.Precision)} | {Formats.Percent(stack.Words?.F1)} | {Formats.Percent(stack.NonPhiRemoved)} | {stack.Missed:N0} |\n"));
        }

        md.Append("\n<details><summary>Recall by corpus label</summary>\n\n| Label | Gold spans | ")
            .AppendJoin(" | ", corpus.Stacks.Select(s => s.Stack))
            .Append(" |\n|---|---:|")
            .Append(string.Concat(corpus.Stacks.Select(_ => "---:|")))
            .Append('\n');
        var labels = corpus.Stacks.Count > 0 ? corpus.Stacks[0].Labels : [];
        foreach (var label in labels)
        {
            md.Append(Formats.Invariant($"| {label.Label} | {label.GoldSpans:N0} | "))
                .AppendJoin(" | ", corpus.Stacks.Select(s => Formats.Percent(s.Labels.FirstOrDefault(l => l.Label == label.Label)?.Recall)))
                .Append(" |\n");
        }

        md.Append("\n</details>\n");
    }
}
