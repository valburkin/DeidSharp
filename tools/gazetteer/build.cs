// Builds the lists in src/DeidSharp.Gazetteer/Data from their public sources. Run it again
// only to update a list; src/DeidSharp.Gazetteer/Data/SOURCES.md says where each file comes
// from and how to download it.
//
//   dotnet run tools/gazetteer/build.cs -- <sources folder> src/DeidSharp.Gazetteer/Data
//
// The sources folder holds, unzipped: Names_2010Census.csv, dist.female.first,
// dist.male.first, 2024_Gaz_place_national.txt and 12dicts' American/2of12.txt.
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

if (args.Length != 2)
{
    Console.Error.WriteLine("Usage: dotnet run tools/gazetteer/build.cs -- <sources folder> <data folder>");
    return 2;
}

var (sources, data) = (args[0], args[1]);
var utf8 = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
var word = new Regex(@"\A\p{L}+(?:['\- ]\p{L}+)*\z", RegexOptions.CultureInvariant);

// Place names may abbreviate a word ("St. Louis", "Ft. Mitchell").
var placeName = new Regex(@"\A\p{L}+\.?(?:['\- ]\p{L}+\.?)*\z", RegexOptions.CultureInvariant);

// Census 2010 surnames: name,rank,count,... ("ALL OTHER NAMES" is a total, not a name).
var surnames = File.ReadLines(Path.Combine(sources, "Names_2010Census.csv")).Skip(1)
    .Select(line => line.Split(','))
    .Where(f => f.Length > 2 && word.IsMatch(f[0]) && f[0] != "ALL OTHER NAMES")
    .Select(f => (Name: f[0].ToLowerInvariant(), Count: int.Parse(f[2], CultureInfo.InvariantCulture)))
    .GroupBy(s => s.Name).Select(g => $"{g.Key}\t{g.Sum(s => s.Count)}");

// Census 1990 first names: "MARY           2.629  2.629      1".
string[] firstNameFiles = ["dist.female.first", "dist.male.first"];
var firstNames = firstNameFiles
    .SelectMany(f => File.ReadLines(Path.Combine(sources, f)))
    .Select(line => line.Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault() ?? "")
    .Where(n => word.IsMatch(n)).Select(n => n.ToLowerInvariant());

// Census 2024 places: the NAME column ends in its legal description ("Abbeville city",
// "Abanda CDP", "Nashville-Davidson metropolitan government (balance)"), which is dropped.
var places = File.ReadLines(Path.Combine(sources, "2024_Gaz_place_national.txt"), Encoding.UTF8).Skip(1)
    .Select(line => line.Split('\t')[3])
    .Select(name => Regex.Replace(name, @"\s*\(.*\)\s*$", ""))
    .Select(name => string.Join(' ', name.Split(' ').Reverse().SkipWhile(w => w == "CDP" || w.All(char.IsLower)).Reverse()))
    .Where(n => placeName.IsMatch(n));

// 12dicts 2of12 (public domain): common English words, base forms, lowercase.
var commonWords = File.ReadLines(Path.Combine(sources, "2of12.txt")).Select(w => w.Trim())
    .Where(w => w.Length > 0 && w.All(c => char.IsLower(c) || c is '\'' or '-'));

Write("surnames.txt", "Census 2010 surnames, lowercase, with how many people had each", surnames);
Write("first-names.txt", "Census 1990 first names, lowercase", firstNames);
Write("places.txt", "Census 2024 places (cities, towns, villages, CDPs), legal description dropped", places);
Write("common-words.txt", "12dicts 2of12: common English words, lowercase", commonWords);
return 0;

void Write(string file, string what, IEnumerable<string> lines)
{
    var sorted = lines.Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
    var header = $"# {what}. Generated by tools/gazetteer/build.cs; sources in SOURCES.md.\n";
    File.WriteAllText(Path.Combine(data, file), header + string.Join('\n', sorted) + "\n", utf8);
    Console.WriteLine(string.Create(CultureInfo.InvariantCulture, $"{file}: {sorted.Count:N0} entries"));
}
